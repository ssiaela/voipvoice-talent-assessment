create or replace function public.hr_publish_settings(p_data jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, private, pg_temp
as $$
declare u uuid; v public.test_versions%rowtype; major_part text; minor_part integer; new_label text;
begin
  u:=private.require_hr(); perform private.validate_test_data(p_data);
  select * into v from public.test_versions where is_current order by id desc limit 1 for update;
  major_part:=coalesce(nullif(split_part(v.label,'.',1),''),'1');
  minor_part:=coalesce(nullif(split_part(v.label,'.',2),'')::integer,0)+1;
  new_label:=major_part||'.'||minor_part;
  update public.test_versions set is_current=false where is_current;
  insert into public.test_versions(label,data,is_current,published_at,created_by) values(new_label,p_data,true,now(),u);
  delete from public.test_draft where id=1;
  insert into public.audit_logs(user_id,event) values(u,'Pubblicata versione test '||new_label);
  return jsonb_build_object('version',new_label);
end;
$$;

create or replace function public.hr_audit()
returns jsonb
language plpgsql
security definer
set search_path = public, private, pg_temp
as $$
declare versions jsonb; logs jsonb;
begin
  perform private.require_hr();
  select coalesce(jsonb_agg(jsonb_build_object(
    'label',v.label,'createdAt',v.published_at,'isCurrent',v.is_current,
    'invitations',(select count(*) from public.invitations i where i.version_id=v.id)
  ) order by v.id desc),'[]'::jsonb) into versions from public.test_versions v;
  select coalesce(jsonb_agg(jsonb_build_object('event',a.event,'createdAt',a.created_at) order by a.id desc),'[]'::jsonb)
  into logs from (select * from public.audit_logs order by id desc limit 100) a;
  return jsonb_build_object('versions',versions,'audit',logs);
end;
$$;

