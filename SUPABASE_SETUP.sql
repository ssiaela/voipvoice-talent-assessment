create or replace function public.hr_get_settings()
returns jsonb
language plpgsql
security definer
set search_path = public, private, pg_temp
as $$
declare v public.test_versions%rowtype; d public.test_draft%rowtype;
begin
  perform private.require_hr();
  select * into v from public.test_versions where is_current order by id desc limit 1;
