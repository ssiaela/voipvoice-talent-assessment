create schema if not exists extensions;
create extension if not exists pgcrypto with schema extensions;
create schema if not exists private;
revoke all on schema private from public, anon, authenticated;
revoke create on schema public from public;

create table if not exists public.hr_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.test_versions (
  id bigint generated by default as identity primary key,
  label text not null unique,
  data jsonb not null,
  is_current boolean not null default false,
  created_at timestamptz not null default now(),
  published_at timestamptz not null default now(),
  created_by uuid references auth.users(id)
);

create table if not exists public.test_draft (
  id integer primary key default 1 check (id = 1),
  data jsonb not null,
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id)
);

create table if not exists public.invitations (
  id bigint generated by default as identity primary key,
  token_hash text not null unique,
  candidate_name text not null,
  position text,
  version_id bigint not null references public.test_versions(id),
  status text not null default 'invited' check (status in ('invited','started','completed')),
  answers jsonb not null default '{}'::jsonb,
  result jsonb,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null,
  completed_at timestamptz,
  created_by uuid references auth.users(id)
);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  user_id uuid references auth.users(id),
  event text not null
);

alter table public.hr_users enable row level security;
alter table public.test_versions enable row level security;
alter table public.test_draft enable row level security;
alter table public.invitations enable row level security;
alter table public.audit_logs enable row level security;

revoke all on table public.hr_users, public.test_versions, public.test_draft, public.invitations, public.audit_logs from anon, authenticated;
revoke all on sequence public.test_versions_id_seq, public.invitations_id_seq, public.audit_logs_id_seq from anon, authenticated;

create or replace function private.token_hash(p_token text)
returns text
language sql
immutable
security definer
set search_path = public, extensions, pg_temp
as $$
  select encode(extensions.digest(coalesce(p_token,''), 'sha256'), 'hex');
$$;

create or replace function private.require_hr()
returns uuid
language plpgsql
stable
security definer
set search_path = public, auth, pg_temp
as $$
declare
  v_user uuid := auth.uid();
begin
  if v_user is null or not exists(select 1 from public.hr_users h where h.user_id=v_user) then
    raise exception 'HR_AUTH_REQUIRED';
  end if;
  return v_user;
end;
$$;

create or replace function private.validate_test_data(p_data jsonb)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  q jsonb;
  a jsonb;
  pri text;
  sec text;
  qid text;
  answer_count integer;
begin
  if p_data is null or jsonb_typeof(p_data) <> 'object' then raise exception 'INVALID_TEST_CONFIG'; end if;
  if jsonb_typeof(p_data->'questions') is distinct from 'array' or jsonb_array_length(p_data->'questions') < 1 then raise exception 'INVALID_TEST_CONFIG'; end if;
  if jsonb_typeof(p_data->'competencies') is distinct from 'array' or jsonb_array_length(p_data->'competencies') < 1 then raise exception 'INVALID_TEST_CONFIG'; end if;
  if jsonb_typeof(p_data->'ranges') is distinct from 'array' or jsonb_array_length(p_data->'ranges') < 1 then raise exception 'INVALID_TEST_CONFIG'; end if;

  if exists(
    select 1 from (
      select value->>'id' as id, count(*) c
      from jsonb_array_elements(p_data->'questions')
      group by value->>'id'
      having count(*) > 1
    ) s
  ) then raise exception 'INVALID_TEST_CONFIG'; end if;

  for q in select value from jsonb_array_elements(p_data->'questions') loop
    qid := q->>'id';
    if qid is null or nullif(trim(q->>'text'),'') is null then raise exception 'INVALID_TEST_CONFIG'; end if;
    if coalesce(q->>'type','') not in ('scale','scenario') then raise exception 'INVALID_TEST_CONFIG'; end if;
    if jsonb_typeof(q->'answers') is distinct from 'array' or jsonb_array_length(q->'answers') < 2 then raise exception 'INVALID_TEST_CONFIG'; end if;
    pri := q->'scoring'->>'primary'; sec := nullif(q->'scoring'->>'secondary','');
    if pri is null or not exists(select 1 from jsonb_array_elements(p_data->'competencies') c where c->>'name'=pri) then raise exception 'INVALID_TEST_CONFIG'; end if;
    if sec is not null and not exists(select 1 from jsonb_array_elements(p_data->'competencies') c where c->>'name'=sec) then raise exception 'INVALID_TEST_CONFIG'; end if;

    select count(*) into answer_count from (
      select value->>'key' k from jsonb_array_elements(q->'answers') group by value->>'key'
    ) x;
    if answer_count <> jsonb_array_length(q->'answers') then raise exception 'INVALID_TEST_CONFIG'; end if;

    for a in select value from jsonb_array_elements(q->'answers') loop
      if nullif(a->>'key','') is null or nullif(a->>'text','') is null or jsonb_typeof(a->'points') is distinct from 'number' then
        raise exception 'INVALID_TEST_CONFIG';
      end if;
    end loop;
  end loop;

  if coalesce((p_data->'weights'->>'primary')::numeric,1) < 0 or coalesce((p_data->'weights'->>'secondary')::numeric,1) < 0 then
    raise exception 'INVALID_TEST_CONFIG';
  end if;
end;
$$;

create or replace function private.validate_answers(p_data jsonb, p_answers jsonb, p_require_all boolean)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  q jsonb;
  k text;
  answer_key text;
  total_keys integer;
begin
  if p_answers is null or jsonb_typeof(p_answers) <> 'object' then raise exception 'INVALID_ANSWER'; end if;
  select count(*) into total_keys from jsonb_object_keys(p_answers);
  if total_keys > 100 then raise exception 'INVALID_ANSWER'; end if;

  for k in select key from jsonb_each(p_answers) loop
    if not exists(select 1 from jsonb_array_elements(p_data->'questions') q2 where q2->>'id'=k) then
      raise exception 'INVALID_ANSWER';
    end if;
  end loop;

  for q in select value from jsonb_array_elements(p_data->'questions') loop
    k := q->>'id';
    if not (p_answers ? k) then
      if p_require_all then raise exception 'MISSING_ANSWER'; end if;
      continue;
    end if;
    answer_key := p_answers->>k;
    if not exists(select 1 from jsonb_array_elements(q->'answers') a where a->>'key'=answer_key) then
      raise exception 'INVALID_ANSWER';
    end if;
  end loop;
end;
$$;

create or replace function private.calculate_result(p_data jsonb, p_answers jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  q jsonb; a jsonb; comp jsonb;
  answer_key text; pri text; sec text; cname text;
  points numeric; selected_points numeric; lo numeric; hi numeric; score numeric;
  primary_weight numeric := coalesce((p_data->'weights'->>'primary')::numeric,1);
  secondary_weight numeric := coalesce((p_data->'weights'->>'secondary')::numeric,1);
  sums jsonb := '{}'::jsonb; weights jsonb := '{}'::jsonb; scores jsonb := '{}'::jsonb;
  scenario_sum numeric := 0; scenario_count integer := 0;
begin
  perform private.validate_answers(p_data,p_answers,true);

  for comp in select value from jsonb_array_elements(p_data->'competencies') loop
    cname := comp->>'name';
    sums := jsonb_set(sums,array[cname],to_jsonb(0::numeric),true);
    weights := jsonb_set(weights,array[cname],to_jsonb(0::numeric),true);
  end loop;

  for q in select value from jsonb_array_elements(p_data->'questions') loop
    answer_key := p_answers->>(q->>'id');
    selected_points := null; lo := null; hi := null;
    for a in select value from jsonb_array_elements(q->'answers') loop
      points := (a->>'points')::numeric;
      if lo is null or points < lo then lo := points; end if;
      if hi is null or points > hi then hi := points; end if;
      if a->>'key'=answer_key then selected_points := points; end if;
    end loop;
    if selected_points is null then raise exception 'INVALID_ANSWER'; end if;
    if coalesce((q->'scoring'->>'inverse')::boolean,false) and q->>'type'='scale' then selected_points := lo + hi - selected_points; end if;
    score := case when hi=lo then 0 else ((selected_points-lo)/(hi-lo))*100 end;

    if q->>'type'='scenario' then scenario_sum:=scenario_sum+score; scenario_count:=scenario_count+1; end if;
    pri := q->'scoring'->>'primary'; sec := nullif(q->'scoring'->>'secondary','');

    if pri is not null and sums ? pri and primary_weight>0 then
      sums := jsonb_set(sums,array[pri],to_jsonb(((sums->>pri)::numeric)+(score*primary_weight)),true);
      weights := jsonb_set(weights,array[pri],to_jsonb(((weights->>pri)::numeric)+primary_weight),true);
    end if;
    if sec is not null and sums ? sec and secondary_weight>0 then
      sums := jsonb_set(sums,array[sec],to_jsonb(((sums->>sec)::numeric)+(score*secondary_weight)),true);
      weights := jsonb_set(weights,array[sec],to_jsonb(((weights->>sec)::numeric)+secondary_weight),true);
    end if;
  end loop;

  for comp in select value from jsonb_array_elements(p_data->'competencies') loop
    cname := comp->>'name';
    scores := jsonb_set(scores,array[cname],to_jsonb(case when (weights->>cname)::numeric=0 then 0 else (sums->>cname)::numeric/(weights->>cname)::numeric end),true);
  end loop;

  return jsonb_build_object(
    'scores',scores,
    'scenarioScore',case when scenario_count=0 then 0 else scenario_sum/scenario_count end,
    'createdAt',now()
  );
end;
$$;

create or replace function public.candidate_get_test(p_token text)
returns jsonb
language plpgsql
security definer
set search_path = public, private, pg_temp
as $$
declare
  inv public.invitations%rowtype; v public.test_versions%rowtype;
  q jsonb; a jsonb; safe_q jsonb; safe_a jsonb; questions jsonb := '[]'::jsonb;
begin
  select * into inv from public.invitations where token_hash=private.token_hash(p_token);
  if not found then raise exception 'LINK_NOT_FOUND'; end if;
  if inv.status<>'completed' and inv.expires_at<now() then raise exception 'LINK_EXPIRED'; end if;
  select * into v from public.test_versions where id=inv.version_id;

  if inv.status<>'completed' then
    for q in select value from jsonb_array_elements(v.data->'questions') loop
      safe_a := '[]'::jsonb;
      for a in select value from jsonb_array_elements(q->'answers') loop
        safe_a := safe_a || jsonb_build_array(jsonb_build_object('key',a->>'key','text',a->>'text'));
      end loop;
      safe_q := jsonb_build_object('id',(q->>'id')::int,'text',q->>'text','type',q->>'type','answers',safe_a);
      questions := questions || jsonb_build_array(safe_q);
    end loop;
  end if;

  return jsonb_build_object(
    'name',inv.candidate_name,'position',inv.position,'version',v.label,'status',inv.status,
    'expiresAt',inv.expires_at,'answers',case when inv.status='completed' then '{}'::jsonb else inv.answers end,
    'questions',questions
  );
end;
$$;

create or replace function public.candidate_start(p_token text)
returns jsonb
language plpgsql
security definer
set search_path = public, private, pg_temp
as $$
declare inv public.invitations%rowtype;
begin
  select * into inv from public.invitations where token_hash=private.token_hash(p_token) for update;
  if not found then raise exception 'LINK_NOT_FOUND'; end if;
  if inv.status='completed' then raise exception 'TEST_COMPLETED'; end if;
  if inv.expires_at<now() then raise exception 'LINK_EXPIRED'; end if;
  update public.invitations set status='started' where id=inv.id and status='invited';
  return jsonb_build_object('ok',true);
end;
$$;

create or replace function public.candidate_save(p_token text, p_answers jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, private, pg_temp
as $$
declare inv public.invitations%rowtype; v public.test_versions%rowtype;
begin
  select * into inv from public.invitations where token_hash=private.token_hash(p_token) for update;
  if not found then raise exception 'LINK_NOT_FOUND'; end if;
  if inv.status='completed' then raise exception 'TEST_COMPLETED'; end if;
  if inv.expires_at<now() then raise exception 'LINK_EXPIRED'; end if;
  select * into v from public.test_versions where id=inv.version_id;
  perform private.validate_answers(v.data,p_answers,false);
  update public.invitations set answers=p_answers,status='started' where id=inv.id;
  return jsonb_build_object('ok',true);
end;
$$;

create or replace function public.candidate_submit(p_token text, p_answers jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, private, pg_temp
as $$
declare inv public.invitations%rowtype; v public.test_versions%rowtype; r jsonb;
begin
  select * into inv from public.invitations where token_hash=private.token_hash(p_token) for update;
  if not found then raise exception 'LINK_NOT_FOUND'; end if;
  if inv.status='completed' then raise exception 'TEST_COMPLETED'; end if;
  if inv.expires_at<now() then raise exception 'LINK_EXPIRED'; end if;
  select * into v from public.test_versions where id=inv.version_id;
  r := private.calculate_result(v.data,p_answers);
  update public.invitations set answers=p_answers,result=r,status='completed',completed_at=now() where id=inv.id;
  insert into public.audit_logs(event) values ('Test completato — candidato #'||inv.id||' — versione '||v.label);
  return jsonb_build_object('ok',true);
end;
$$;

create or replace function public.hr_bootstrap()
returns jsonb
language plpgsql
security definer
set search_path = public, private, auth, pg_temp
as $$
declare u uuid; v public.test_versions%rowtype; email_value text;
begin
  u:=private.require_hr();
  select * into v from public.test_versions where is_current order by id desc limit 1;
  select email into email_value from auth.users where id=u;
  return jsonb_build_object('currentVersion',v.label,'email',email_value);
end;
$$;

create or replace function public.hr_list_candidates()
returns jsonb
language plpgsql
security definer
set search_path = public, private, pg_temp
as $$
declare items jsonb;
begin
  perform private.require_hr();
  select coalesce(jsonb_agg(jsonb_build_object(
    'id',i.id,'name',i.candidate_name,'position',i.position,'version',v.label,
    'status',case when i.status<>'completed' and i.expires_at<now() then 'expired' else i.status end,
    'createdAt',i.created_at,'expiresAt',i.expires_at,'completedAt',i.completed_at
  ) order by i.created_at desc),'[]'::jsonb)
  into items
  from public.invitations i join public.test_versions v on v.id=i.version_id;
  return jsonb_build_object('items',items);
end;
$$;

create or replace function public.hr_create_invitation(p_name text, p_position text default null, p_expiry_days integer default 14)
returns jsonb
language plpgsql
security definer
set search_path = public, private, extensions, pg_temp
as $$
declare u uuid; v public.test_versions%rowtype; tok text; new_id bigint; exp timestamptz;
begin
  u:=private.require_hr();
  if nullif(trim(p_name),'') is null then raise exception 'Nome candidato obbligatorio'; end if;
  if p_expiry_days<1 or p_expiry_days>90 then raise exception 'Scadenza non valida'; end if;
  select * into v from public.test_versions where is_current order by id desc limit 1;
  tok:=encode(extensions.gen_random_bytes(24),'hex'); exp:=now()+make_interval(days=>p_expiry_days);
  insert into public.invitations(token_hash,candidate_name,position,version_id,expires_at,created_by)
  values(private.token_hash(tok),trim(p_name),nullif(trim(coalesce(p_position,'')),''),v.id,exp,u) returning id into new_id;
  insert into public.audit_logs(user_id,event) values(u,'Creato invito #'||new_id||' — versione '||v.label);
  return jsonb_build_object('id',new_id,'token',tok,'version',v.label,'expiresAt',exp);
end;
$$;

create or replace function public.hr_rotate_invitation_token(p_invitation_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public, private, extensions, pg_temp
as $$
declare u uuid; inv public.invitations%rowtype; tok text;
begin
  u:=private.require_hr();
  select * into inv from public.invitations where id=p_invitation_id for update;
  if not found then raise exception 'INVITATION_NOT_FOUND'; end if;
  if inv.status='completed' then raise exception 'TEST_COMPLETED'; end if;
  tok:=encode(extensions.gen_random_bytes(24),'hex');
  update public.invitations set token_hash=private.token_hash(tok) where id=inv.id;
  insert into public.audit_logs(user_id,event) values(u,'Rigenerato link invito #'||inv.id);
  return jsonb_build_object('token',tok,'expiresAt',inv.expires_at);
end;
$$;

