$$;

create or replace function public.hr_save_draft(p_data jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, private, pg_temp
as $$
declare u uuid;
begin
  u:=private.require_hr(); perform private.validate_test_data(p_data);
  insert into public.test_draft(id,data,updated_at,updated_by) values(1,p_data,now(),u)
  on conflict(id) do update set data=excluded.data,updated_at=excluded.updated_at,updated_by=excluded.updated_by;
  insert into public.audit_logs(user_id,event) values(u,'Salvata bozza configurazione test');
  return jsonb_build_object('ok',true);
end;
$$;

